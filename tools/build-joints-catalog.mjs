// Dev tool: public/injuries-catalog.js (joint tags of the dataset exercises, from tools/joint-rules.mjs) and the review list docs/injury-tags-catalog.md.
//   node tools/build-joints-catalog.mjs
import fs from "node:fs";
import { CATALOG } from "../public/exercise-catalog.js";
import { jointRules } from "./joint-rules.mjs";

const AREA_EN = { shoulder: "Shoulder", elbow: "Elbow", wrist: "Wrist", "lower-back": "Lower back", hip: "Hip", knee: "Knee", ankle: "Ankle" };
const meta = JSON.parse(fs.readFileSync(new URL("./catalog-meta.json", import.meta.url), "utf8"));
const table = {}, byGroup = {};
for (const [name, group] of CATALOG.map(r => [r[0], r[1]])) {
  const m = meta[name]; const areas = jointRules({ name: m.dataset, equipment: m.equipment, category: m.category }, group);
  table[name] = areas; (byGroup[group] ||= []).push(name);
}
fs.writeFileSync(new URL("../public/injuries-catalog.js", import.meta.url),
`// Generated by tools/build-joints-catalog.mjs from tools/joint-rules.mjs. Do not edit; fix the rules or add an override there. Merged into JOINTS by injuries.js.
export const JOINTS_CATALOG = {
${Object.entries(table).map(([n, a]) => ` ${JSON.stringify(n)}: ${JSON.stringify(a)}`).join(",\n")}
};
`);
let md = `# Injury tags of the dataset exercises (review list)

Generated by \`node tools/build-joints-catalog.mjs\` from the rules in \`tools/joint-rules.mjs\`; do not edit by hand. The rules are conservative (more joints rather than fewer). To change one exercise, add an override to \`OVERRIDES\` in \`tools/joint-rules.mjs\` and rerun.\n\n`;
for (const [g, names] of Object.entries(byGroup)) {
  md += `## ${g}\n\n| Exercise | Joints loaded |\n|---|---|\n` + names.map(n => `| ${n} | ${table[n].length ? table[n].map(a => AREA_EN[a]).join(", ") : "none"} |`).join("\n") + "\n\n";
}
md += `## Count per area\n\n| Area | Exercises |\n|---|---|\n` + Object.keys(AREA_EN).map(a => `| ${AREA_EN[a]} | ${Object.values(table).filter(l => l.includes(a)).length} |`).join("\n") + "\n";
fs.writeFileSync(new URL("../docs/injury-tags-catalog.md", import.meta.url), md);
console.log("tags:", Object.keys(table).length, "| none:", Object.values(table).filter(l => !l.length).length, "| per area:", Object.keys(AREA_EN).map(a => a + "=" + Object.values(table).filter(l => l.includes(a)).length).join(" "));
