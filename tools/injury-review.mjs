// Writes docs/injury-tags.md: the joint table of public/injuries.js as a review list for the owner, grouped by muscle.
// Run from the repo root: node tools/injury-review.mjs
// Corrections are edits to the JOINTS table in public/injuries.js; then run this again.
import { writeFileSync } from "node:fs";
import { LIB, MUSCLES } from "../public/exercise-library.js";
import { AREAS, AREA_EN, JOINTS } from "../public/injuries.js";
import { AR } from "../public/lang-ar.js";

const label = id => `${AREA_EN[id]} (${AR.names.area[id]})`;
let md = `# Injury tags: which joints each exercise loads

Generated by \`node tools/injury-review.mjs\` from \`public/injuries.js\`. **Do not edit this file by hand**: correct the \`JOINTS\` table in \`public/injuries.js\`, then run the generator again.

An area is listed when the movement puts real load on that joint or holds it in a stressed position. A person who marks an area (for example Knee) no longer gets suggestions for any exercise that lists it. Exercises already on their days or in their history stay, with a warning.

Areas: ${AREAS.map(label).join(", ")}.

`;
for (const g of MUSCLES) {
  md += `## ${g}\n\n| Exercise | Joints loaded |\n|---|---|\n`;
  for (const name of LIB[g]) md += `| ${name} | ${JOINTS[name].length ? JOINTS[name].map(a => AREA_EN[a]).join(", ") : "none"} |\n`;
  md += "\n";
}
md += `## Count per area\n\n| Area | Exercises |\n|---|---|\n`;
for (const a of AREAS) md += `| ${AREA_EN[a]} | ${Object.values(JOINTS).filter(l => l.includes(a)).length} |\n`;
writeFileSync(new URL("../docs/injury-tags.md", import.meta.url), md);
console.log("wrote docs/injury-tags.md");
