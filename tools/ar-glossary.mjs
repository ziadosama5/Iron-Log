export const ENTRIES = new Map();
for (const line of GLOSSARY.split("\n")) {
  const m = /^(\S+) (.+?) = ?(.*)$/.exec(line.trim());
  if (!m) continue;
  ENTRIES.set(m[2], { cat: m[1], ar: m[3] });
}
const MAX_PHRASE = Math.max(...[...ENTRIES.keys()].map(k => k.split(" ").length));

const tokenize = name => String(name).toLowerCase().replace(/в°/g, "°").replace(/[(),.]/g, " ").replace(/-/g, " ").replace(/\s+/g, " ").trim().split(" ").filter(Boolean);

// -> { ar, unknown: [english words with no glossary entry] }
export function composeArabic(name) {
  const toks = tokenize(name), items = [], unknown = [];
  for (let i = 0; i < toks.length;) {
    let hit = null, len = 0;
    for (let n = Math.min(MAX_PHRASE, toks.length - i); n >= 1; n--) {
      const key = toks.slice(i, i + n).join(" ");
      if (ENTRIES.has(key)) { hit = ENTRIES.get(key); len = n; break; }
    }
    if (!hit) { unknown.push(toks[i]); i++; continue; }
    if (hit.cat !== "X" && hit.ar) items.push(hit);
    i += len;
  }
  const by = (...cats) => items.filter(x => cats.includes(x.cat)).map(x => x.ar);
  const dedupe = list => list.filter((x, i) => list.indexOf(x) === i);
  if (!by("M").length && !by("O").length && !by("N").length) items.unshift({ cat: "M", ar: "تمرين" });
  const parts = [...dedupe(by("M")), ...dedupe(by("O")), ...dedupe(by("N")), ...dedupe(by("A1")), ...dedupe(by("A2")), ...dedupe(by("A4")), ...dedupe(by("A3")), ...dedupe(by("E"))];
  return { ar: parts.join(" ").replace(/\s+/g, " ").trim(), unknown };
}
