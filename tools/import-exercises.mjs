// Builds the exercise info data and drawings. Dev tool; the app never runs this.
//   node tools/import-exercises.mjs           download missing drawings, regenerate exercise-info.js
//   node tools/import-exercises.mjs --force   re-download every drawing
// Edit tools/exercise-sources.json, then run this. Drawings come from Everkinetic (CC BY-SA 4.0).
import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync, unlinkSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { recolorSvg, slugify, posesFor, applyDrawingReuse } from "./svg-tools.mjs";
import { ALL_EX, ALIASES } from "../public/exercise-library.js";
import { DRAWINGS } from "./draw-exercises.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "public", "exercises");
const infoFile = join(root, "public", "exercise-info.js");
const EK = "https://raw.githubusercontent.com/everkinetic/data/main/dist/svg/";

const force = process.argv.includes("--force");

function fail(msg) { console.error("import-exercises: " + msg); process.exit(1); }

const sources = JSON.parse(readFileSync(join(root, "tools", "exercise-sources.json"), "utf8"));
const names = Object.keys(sources);
const missing = ALL_EX.filter(n => !names.includes(n)), extra = names.filter(n => !ALL_EX.includes(n));
if (missing.length || extra.length) fail(`sources don't match the library. Missing: ${missing.join(", ") || "-"}. Extra: ${extra.join(", ") || "-"}`);

mkdirSync(outDir, { recursive: true });
const wanted = new Set();
const info = {};

for (const name of names.slice().sort((a, b) => a.localeCompare(b))) {
  const s = sources[name], slug = slugify(name);
  if (s.draw) {
    // Hand-drawn in tools/draw-exercises.mjs (no download): written straight from the drawing code.
    if (!DRAWINGS[slug]) fail(`${name}: no drawing for "${slug}" in tools/draw-exercises.mjs`);
    for (const suffix of ["start", "end"]) {
      const file = `${slug}-${suffix}.svg`;
      wanted.add(file);
      const text = DRAWINGS[slug][suffix] + "\n";
      if (!existsSync(join(outDir, file)) || readFileSync(join(outDir, file), "utf8") !== text) { writeFileSync(join(outDir, file), text); console.log("drew", file); }
    }
  } else if (s.ek) {
    for (const [pose, suffix] of posesFor(s)) {
      const file = `${slug}-${suffix}.svg`;
      wanted.add(file);
      if (!force && existsSync(join(outDir, file))) continue;
      const res = await fetch(`${EK}${s.ek}-${pose}.svg`);
      if (!res.ok) fail(`${name}: download of ${s.ek}-${pose} failed (${res.status})`);
      let svg;
      try { svg = recolorSvg(await res.text(), `${s.ek}-${pose}`); } catch (e) { fail(`${name}: ${e.message}`); }
      writeFileSync(join(outDir, file), svg + "\n");
      console.log("wrote", file);
    }
  }
  info[name.toLowerCase()] = { name, slug, img: !!(s.ek || s.draw), ...(s.draw ? { own: true } : {}), primary: s.primary, secondary: s.secondary, tips: s.tips, ...(s.ar ? { ar: s.ar } : {}) };
}

applyDrawingReuse(info, sources);

for (const f of readdirSync(outDir)) {
  if (f.endsWith(".svg") && !wanted.has(f)) { unlinkSync(join(outDir, f)); console.log("removed", f); }
}

writeFileSync(infoFile,
  "// Generated by tools/import-exercises.mjs. Edit tools/exercise-sources.json instead, then rerun it.\n" +
  "// Drawings: /exercises/<slug>-start.svg and -end.svg (adapted from Everkinetic, CC BY-SA 4.0).\n" +
  "export const INFO = " + JSON.stringify(info, null, 1) + ";\n\n" +
  "const ALIASES = " + JSON.stringify(Object.fromEntries(Object.entries(ALIASES).map(([k, v]) => [k, v.toLowerCase()]))) + ";\n" +
  "export function infoFor(name) { const k = String(name).toLowerCase(); return INFO[k] || INFO[ALIASES[k]] || null; }\n");
console.log(`exercise-info.js: ${names.length} exercises, ${Object.values(info).filter(e => e.img).length} with drawings`);
