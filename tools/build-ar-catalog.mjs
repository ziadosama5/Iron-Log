// Dev tool: builds public/lang-ar-catalog.js (Arabic names of the catalog exercises) from the glossary composer plus the hand fixes in
// tools/ar-names/overrides.json, and writes the review table docs/arabic-names-catalog.md.   node tools/build-ar-catalog.mjs
import fs from "node:fs";
import { CATALOG } from "../public/exercise-catalog.js";
import { composeArabic } from "./ar-glossary.mjs";

const overrides = JSON.parse(fs.readFileSync(new URL("./ar-names/overrides.json", import.meta.url), "utf8"));
const out = {}, rows = [], problems = [];
for (const [name, group] of CATALOG.map(r => [r[0], r[1]])) {
  const c = composeArabic(name), hand = Object.hasOwn(overrides, name);
  const ar = hand ? overrides[name] : c.ar;
  if (c.unknown.length && !hand) problems.push(`${name}: unknown words ${c.unknown.join(", ")}`);
  out[name] = ar; rows.push({ name, group, ar, hand });
}
if (problems.length) { console.error(problems.join("\n")); process.exit(1); }
fs.writeFileSync(new URL("../public/lang-ar-catalog.js", import.meta.url),
`// Generated by tools/build-ar-catalog.mjs (glossary in tools/ar-glossary.mjs, hand fixes in tools/ar-names/overrides.json). Do not edit.
// Arabic names of the dataset exercises, merged into AR.names.ex by lang-ar.js. A first draft: the review table is docs/arabic-names-catalog.md.
export const AR_CATALOG_EX = ${JSON.stringify(out, null, 1)};
`);
fs.writeFileSync(new URL("../docs/arabic-names-catalog.md", import.meta.url),
`# Arabic names of the dataset exercises (review table)

Machine-composed from a glossary (\`tools/ar-glossary.mjs\`), a first draft in plain Modern Standard Arabic. To fix a name: add it to \`tools/ar-names/overrides.json\` (English name -> Arabic) and run \`node tools/build-ar-catalog.mjs\`. "hand" = already fixed by hand.

| Group | English | Arabic | |
|---|---|---|---|
` + rows.map(r => `| ${r.group} | ${r.name} | ${r.ar} | ${r.hand ? "hand" : ""} |`).join("\n") + "\n");
const dup = rows.filter((r, i) => rows.findIndex(x => x.ar === r.ar) !== i);
console.log("names:", rows.length, "| hand fixes:", rows.filter(r => r.hand).length, "| duplicate Arabic names:", dup.length, dup.map(d => d.name).join("; "));
