// Dev tool: turns hasaneyldrm/exercises-dataset (names, targets, equipment: MIT; pictures: (c) Gym visual) into the generated catalog.
//
//   node tools/import-catalog.mjs --data <path to data/exercises.json of the dataset>
//
// Writes public/exercise-catalog.js (eager rows), tools/catalog-meta.json (the dataset's own name/equipment/target per row, used by
// tests) and, in Task 6, public/exercise-howto.js. Skipped: duplicates folded by foldKey (v. N, male/female, pov), exercises whose picture
// a curated exercise already uses, and names equal to a curated exercise.
import fs from "node:fs";
import { titleCase, foldKey, groupFor, eqIdsFor, isHoldKind, groupsOfWords } from "./catalog-maps.mjs";
import { CURATED } from "../public/exercise-library.js";

const arg = n => { const i = process.argv.indexOf(n); return i > 0 ? process.argv[i + 1] : null; };
const dataPath = arg("--data") || (console.error("--data <exercises.json> required"), process.exit(1));
const data = JSON.parse(fs.readFileSync(dataPath, "utf8")).sort((a, b) => a.id.localeCompare(b.id));
const curatedGifs = new Set(Object.values(JSON.parse(fs.readFileSync(new URL("./exercise-gifs.json", import.meta.url), "utf8"))).filter(Boolean));
const GROUPS = ["Chest", "Back", "Shoulders", "Biceps", "Triceps", "Quads", "Hamstrings & Glutes", "Calves", "Core"];

// the curated names come from the library itself, but this tool must also work after the catalog is merged: use the curated set only
const normKey = n => n.toLowerCase().replace(/[^a-z0-9]+/g, "");   // "Pull-up" and "Pull Up" are one exercise
const curatedNames = new Set([...CURATED].map(normKey));
const seenFold = new Set(), seenName = new Set(), rows = [], meta = {};
let foldedAway = 0, curatedPic = 0, curatedName = 0;
for (const e of data) {
  const key = foldKey(e.name);
  if (seenFold.has(key)) { foldedAway++; continue; }
  seenFold.add(key);
  const gif = `${e.id}-${e.media_id}`;
  if (curatedGifs.has(gif)) { curatedPic++; continue; }
  const name = titleCase(foldKey(e.name).replace(/\s+/g, " "));
  const lower = normKey(name);
  if (curatedNames.has(lower)) { curatedName++; continue; }
  if (seenName.has(lower)) { foldedAway++; continue; }
  seenName.add(lower);
  rows.push({ name, group: groupFor(e), eq: eqIdsFor(e), gif, kind: isHoldKind(e) ? "hold" : "", e });
}
rows.sort((a, b) => GROUPS.indexOf(a.group) - GROUPS.indexOf(b.group) || a.name.localeCompare(b.name));
for (const r of rows) meta[r.name] = { dataset: r.e.name, equipment: r.e.equipment, target: r.e.target, category: r.e.category };

const body = rows.map(r => "  " + JSON.stringify([r.name, r.group, r.eq, r.gif, r.kind])).join(",\n");
fs.writeFileSync(new URL("../public/exercise-catalog.js", import.meta.url),
`// Generated by tools/import-catalog.mjs from hasaneyldrm/exercises-dataset (names/targets/equipment MIT; the pictures are (c) Gym visual). Do not edit.
// Row: [name, muscle group, equipment ids (none = body weight), picture id ("<id>-<media_id>"), kind ("" = weight x reps, "hold" = seconds)].
export const CATALOG = [
${body}
];
export const CATALOG_HOLDS = new Set(CATALOG.filter(r => r[4] === "hold").map(r => r[0].toLowerCase()));
`);
fs.writeFileSync(new URL("./catalog-meta.json", import.meta.url), JSON.stringify(meta, null, 1) + "\n");

// The English How-to (lazy, loaded when an info sheet opens): steps and the other muscle groups the exercise works.
const howto = {};
for (const r of rows) {
  const steps = ((r.e.instruction_steps && r.e.instruction_steps.en) || []).map(x => String(x).trim()).filter(Boolean);
  const also = groupsOfWords([...(r.e.secondary_muscles || []), r.e.muscle_group], r.group);
  howto[r.name.toLowerCase()] = { s: also, steps: steps.length ? steps : [String((r.e.instructions && r.e.instructions.en) || "").trim()].filter(Boolean) };
}
fs.writeFileSync(new URL("../public/exercise-howto.js", import.meta.url),
`// Generated by tools/import-catalog.mjs (steps: MIT-licensed text of hasaneyldrm/exercises-dataset). Loaded lazily by the info sheet. Do not edit.
// { "<lowercase exercise name>": { s: [other muscle groups it works], steps: [English sentences] } }
export const HOWTO = ${JSON.stringify(howto)};
`);

const count = f => rows.reduce((o, r) => { const k = f(r); o[k] = (o[k] || 0) + 1; return o; }, {});
console.log("rows:", rows.length, "| folded duplicates:", foldedAway, "| curated picture:", curatedPic, "| curated name:", curatedName);
console.log("by group:", JSON.stringify(count(r => r.group)));
console.log("holds:", rows.filter(r => r.kind).length, "| by equipment id:", JSON.stringify(count(r => r.eq.join("+") || "bodyweight")).slice(0, 600));
